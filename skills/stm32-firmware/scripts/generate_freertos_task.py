#!/usr/bin/env python3
"""
Generate boilerplate FreeRTOS task code for STM32 projects.
"""

import sys
import os
from datetime import datetime

def generate_task_code(task_name, stack_size=512, priority=2, use_queue=False, use_semaphore=False):
    """
    Generate FreeRTOS task code with optional IPC mechanisms.
    
    Args:
        task_name: Name of the task (e.g., "SensorRead")
        stack_size: Stack size in words (default 512 words = 2KB)
        priority: Task priority (default 2)
        use_queue: Add queue example code
        use_semaphore: Add semaphore example code
    """
    
    # Sanitize task name
    task_name = task_name.replace(" ", "_")
    task_upper = task_name.upper()
    task_lower = task_name.lower()
    
    # Generate header file
    header_content = f'''/**
  ******************************************************************************
  * @file           : {task_lower}.h
  * @brief          : Header for {task_lower}.c file
  * @author         : Generated by FreeRTOS Task Generator
  * @date           : {datetime.now().strftime("%Y-%m-%d")}
  ******************************************************************************
  */

#ifndef {task_upper}_H
#define {task_upper}_H

#ifdef __cplusplus
extern "C" {{
#endif

/* Includes ------------------------------------------------------------------*/
#include "FreeRTOS.h"
#include "task.h"
{"#include \"queue.h\"" if use_queue else ""}
{"#include \"semphr.h\"" if use_semaphore else ""}
#include <stdint.h>

/* Exported constants --------------------------------------------------------*/
#define {task_upper}_STACK_SIZE     {stack_size}U
#define {task_upper}_PRIORITY       (tskIDLE_PRIORITY + {priority}U)
#define {task_upper}_DELAY_MS       100U

/* Exported types ------------------------------------------------------------*/
typedef struct {{
    uint32_t counter;
    uint8_t status;
}} {task_name}Data_t;

/* Exported variables --------------------------------------------------------*/
extern TaskHandle_t x{task_name}Handle;
{"extern QueueHandle_t x" + task_name + "Queue;" if use_queue else ""}
{"extern SemaphoreHandle_t x" + task_name + "Semaphore;" if use_semaphore else ""}

/* Exported functions --------------------------------------------------------*/
void {task_name}_Init(void);
void {task_name}_Task(void* pvParameters);

#ifdef __cplusplus
}}
#endif

#endif /* {task_upper}_H */
'''

    # Generate source file
    source_content = f'''/**
  ******************************************************************************
  * @file           : {task_lower}.c
  * @brief          : {task_name} task implementation
  * @author         : Generated by FreeRTOS Task Generator
  * @date           : {datetime.now().strftime("%Y-%m-%d")}
  ******************************************************************************
  */

/* Includes ------------------------------------------------------------------*/
#include "{task_lower}.h"
#include "main.h"

/* Private typedef -----------------------------------------------------------*/

/* Private define ------------------------------------------------------------*/
{f"#define {task_upper}_QUEUE_LENGTH    10U" if use_queue else ""}

/* Private macro -------------------------------------------------------------*/

/* Private variables ---------------------------------------------------------*/
TaskHandle_t x{task_name}Handle = NULL;
{"QueueHandle_t x" + task_name + "Queue = NULL;" if use_queue else ""}
{"SemaphoreHandle_t x" + task_name + "Semaphore = NULL;" if use_semaphore else ""}

/* Private function prototypes -----------------------------------------------*/
static void {task_name}_ProcessData({task_name}Data_t* pData);

/* Private functions ---------------------------------------------------------*/

/**
  * @brief  Initialize {task_name} task and resources
  * @retval None
  */
void {task_name}_Init(void)
{{
{f'''    /* Create queue */
    x{task_name}Queue = xQueueCreate({task_upper}_QUEUE_LENGTH, sizeof({task_name}Data_t));
    if (x{task_name}Queue == NULL) {{
        Error_Handler();
    }}
''' if use_queue else ""}
{f'''    /* Create semaphore */
    x{task_name}Semaphore = xSemaphoreCreateBinary();
    if (x{task_name}Semaphore == NULL) {{
        Error_Handler();
    }}
''' if use_semaphore else ""}
    /* Create task */
    BaseType_t xReturned = xTaskCreate(
        {task_name}_Task,
        "{task_name}",
        {task_upper}_STACK_SIZE,
        NULL,
        {task_upper}_PRIORITY,
        &x{task_name}Handle
    );
    
    if (xReturned != pdPASS) {{
        Error_Handler();
    }}
}}

/**
  * @brief  {task_name} task function
  * @param  pvParameters: Not used
  * @retval None
  */
void {task_name}_Task(void* pvParameters)
{{
    /* Remove compiler warning about unused parameter */
    (void)pvParameters;
    
    {task_name}Data_t taskData = {{0}};
    
    /* Infinite loop */
    for (;;)
    {{
{f'''        /* Wait for semaphore */
        if (xSemaphoreTake(x{task_name}Semaphore, portMAX_DELAY) == pdPASS)
        {{
            /* Semaphore acquired - process event */
            taskData.counter++;
        }}
''' if use_semaphore else f'''        /* Periodic task execution */
        taskData.counter++;
'''}
{f'''        /* Send data to queue */
        if (xQueueSend(x{task_name}Queue, &taskData, pdMS_TO_TICKS(100U)) != pdPASS)
        {{
            /* Queue full - handle error */
        }}
''' if use_queue else ""}        
        /* Process task data */
        {task_name}_ProcessData(&taskData);
        
        /* Delay for next iteration */
        vTaskDelay(pdMS_TO_TICKS({task_upper}_DELAY_MS));
    }}
}}

/**
  * @brief  Process task data
  * @param  pData: Pointer to task data structure
  * @retval None
  */
static void {task_name}_ProcessData({task_name}Data_t* pData)
{{
    /* Add task-specific processing here */
    
    /* Example: Update status based on counter */
    if (pData->counter > 100U) {{
        pData->status = 1U;
        pData->counter = 0U;
    }} else {{
        pData->status = 0U;
    }}
}}

/* Exported functions --------------------------------------------------------*/

/************************ (C) COPYRIGHT STMicroelectronics *****END OF FILE****/
'''

    return header_content, source_content


def main():
    if len(sys.argv) < 2:
        print("Usage: python generate_freertos_task.py <TaskName> [options]")
        print("Options:")
        print("  --stack-size SIZE    Stack size in words (default: 512)")
        print("  --priority PRIO      Task priority (default: 2)")
        print("  --queue              Include queue example")
        print("  --semaphore          Include semaphore example")
        print("  --output PATH        Output directory (default: current)")
        print()
        print("Example:")
        print("  python generate_freertos_task.py SensorRead --queue --stack-size 256")
        sys.exit(1)
    
    task_name = sys.argv[1]
    stack_size = 512
    priority = 2
    use_queue = False
    use_semaphore = False
    output_dir = "."
    
    # Parse arguments
    i = 2
    while i < len(sys.argv):
        if sys.argv[i] == "--stack-size" and i + 1 < len(sys.argv):
            stack_size = int(sys.argv[i + 1])
            i += 2
        elif sys.argv[i] == "--priority" and i + 1 < len(sys.argv):
            priority = int(sys.argv[i + 1])
            i += 2
        elif sys.argv[i] == "--queue":
            use_queue = True
            i += 1
        elif sys.argv[i] == "--semaphore":
            use_semaphore = True
            i += 1
        elif sys.argv[i] == "--output" and i + 1 < len(sys.argv):
            output_dir = sys.argv[i + 1]
            i += 2
        else:
            print(f"Unknown option: {sys.argv[i]}")
            sys.exit(1)
    
    # Generate code
    header, source = generate_task_code(task_name, stack_size, priority, use_queue, use_semaphore)
    
    # Create output directory if it doesn't exist
    os.makedirs(output_dir, exist_ok=True)
    
    # Write files
    task_lower = task_name.lower().replace(" ", "_")
    header_path = os.path.join(output_dir, f"{task_lower}.h")
    source_path = os.path.join(output_dir, f"{task_lower}.c")
    
    with open(header_path, 'w') as f:
        f.write(header)
    
    with open(source_path, 'w') as f:
        f.write(source)
    
    print(f"✅ Generated FreeRTOS task files:")
    print(f"   {header_path}")
    print(f"   {source_path}")
    print()
    print("Next steps:")
    print(f"1. Add '{task_lower}.c' to your project")
    print(f"2. Include '{task_lower}.h' in main.c")
    print(f"3. Call {task_name}_Init() before starting scheduler")


if __name__ == "__main__":
    main()
